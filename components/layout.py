"""Page-level building blocks: CSS loading, headers, section titles, cards."""

from __future__ import annotations

import base64
import io
from contextlib import contextmanager
from html import escape
from typing import Iterator

import streamlit as st
from PIL import Image

from config import APP_NAME, APP_VERSION, STYLES_PATH


@st.cache_data(show_spinner=False)
def _read_css(path: str, mtime: float) -> str:  # mtime busts the cache on edit
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def load_css() -> None:
    st.html(f"<style>{_read_css(str(STYLES_PATH), STYLES_PATH.stat().st_mtime)}</style>")


def page_header(eyebrow: str, title: str, lede: str | None = None) -> None:
    lede_html = f'<p class="fv-lede">{lede}</p>' if lede else ""
    st.html(
        f'<header class="fv-page-header">'
        f'<div class="fv-eyebrow">{escape(eyebrow)}</div>'
        f'<div class="fv-title" role="heading" aria-level="1">{escape(title)}</div>'
        f"{lede_html}</header>"
    )


def section_title(title: str, aside: str | None = None) -> None:
    aside_html = f"<span>{escape(aside)}</span>" if aside else ""
    st.html(f'<div class="fv-section-title"><h3>{escape(title)}</h3>{aside_html}</div>')


def notice(label: str, text: str) -> None:
    st.html(f'<div class="fv-notice"><strong>{escape(label)}</strong><div>{text}</div></div>')


def demo_notice() -> None:
    notice(
        "Demo mode",
        "Predictions, embeddings and similarity scores on this page are generated by mock "
        "services for demonstration. No trained model is connected yet.",
    )


def card_heading(title: str, subtitle: str | None = None) -> None:
    sub = f'<p class="fv-card-sub">{subtitle}</p>' if subtitle else '<div style="height:.6rem"></div>'
    st.html(f'<div class="fv-card-title">{escape(title)}</div>{sub}')


@contextmanager
def card(key: str) -> Iterator[None]:
    """White bordered card. Styling hooks onto the ``st-key-card_*`` class."""
    with st.container(key=f"card_{key}"):
        yield


def footer() -> None:
    st.html(
        f'<footer class="fv-footer"><span>{escape(APP_NAME)} &middot; University project</span>'
        f"<span>Frontend demo v{escape(APP_VERSION)} &middot; Mock data, no live inference</span></footer>"
    )


def image_to_data_uri(image: Image.Image, fmt: str = "JPEG", max_side: int = 640) -> str:
    img = image.copy()
    img.thumbnail((max_side, max_side))
    if fmt == "JPEG" and img.mode not in ("RGB", "L"):
        img = img.convert("RGB")
    buffer = io.BytesIO()
    img.save(buffer, format=fmt, quality=85)
    mime = "jpeg" if fmt == "JPEG" else fmt.lower()
    return f"data:image/{mime};base64,{base64.b64encode(buffer.getvalue()).decode()}"


def kv_grid(items: list[tuple[str, str]], columns: int = 2) -> str:
    cls = "fv-kv fv-kv--3" if columns == 3 else "fv-kv"
    cells = "".join(f"<div><dt>{escape(k)}</dt><dd>{escape(v)}</dd></div>" for k, v in items)
    return f'<dl class="{cls}">{cells}</dl>'
